from __future__ import annotations

import re

STOP = {
    "и", "в", "во", "на", "с", "со", "по", "для", "от", "до", "из", "к", "о", "об", "а", "но", "что",
    "это", "как", "бы", "же", "ли", "не", "ни", "у", "я", "мне", "мой", "хочу", "хочется", "нужна",
    "нужно", "игра", "игру", "игры", "чтобы", "или", "там", "тут", "очень", "такая", "такую",
    "какая", "какую", "найди", "подбери", "посоветуй", "the", "a", "an", "of", "and", "or", "to",
}

_TOKEN = re.compile(r"[a-zа-яё0-9]+", re.I)


def tokens(text: str) -> list[str]:
    return [t for t in _TOKEN.findall(text.lower().replace("ё", "е")) if t not in STOP]


# Небольшой словарь синонимов (по основам из 4 букв), чтобы «вдвоём» находило «кооператив».
SYNONYMS = {
    "вдво": "кооп", "друз": "кооп", "друг": "кооп", "вмес": "кооп", "напа": "кооп",
    "ужас": "хорр", "жутк": "стра", "спок": "расс", "стре": "шуте", "ребе": "дете",
    "фент": "фэнт", "фант": "фэнт", "хард": "слож", "труд": "слож", "леги": "прос",
}


def stem(token: str, n: int = 4) -> str:
    """Грубый «стеммер»: обрезаем слово до n символов («атмосферная»/«атмосферное» → «атмо»)
    и заменяем несколько частых синонимов. Для русского языка этого достаточно для демо-режима."""
    s = token[:n]
    return SYNONYMS.get(s, s)


def stems(text: str) -> list[str]:
    return [stem(t) for t in tokens(text)]


def norm_title(text: str) -> str:
    return " ".join(_TOKEN.findall(text.lower().replace("ё", "е")))
